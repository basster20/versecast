"""Convert the KJV canon into a JS module the app can load from file://.

Input : ../../_internal/canons/KJV/verses.json   (flat {"Book C:V": text})
Output: ../assets/js/data.js                    (window.CANON, grouped by book/chapter)

Grouping matters: a flat 31k-key object costs ~4.7 MB and a lot of parse time;
book -> chapter -> verse keeps the same information in a smaller, faster shape.
"""
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(os.path.dirname(ROOT), "_internal", "canons", "KJV", "verses.json")
OUT = os.path.join(ROOT, "assets", "js", "data.js")

KEY_RE = re.compile(r"^(?P<book>.+?)\s+(?P<chapter>\d+):(?P<verse>\d+)$")


def main():
    with open(SRC, encoding="utf-8") as fh:
        flat = json.load(fh)

    canon = {}
    order = []
    count = 0
    for key, text in flat.items():
        m = KEY_RE.match(key)
        if not m:
            raise SystemExit(f"unparsed key: {key!r}")
        book = m.group("book")
        if book not in canon:
            canon[book] = {}
            order.append(book)
        chapter = m.group("chapter")
        canon[book].setdefault(chapter, {})[m.group("verse")] = text.strip()
        count += 1

    payload = {
        "translation": "KJV",
        "title": "King James Version",
        "verses": count,
        "books": order,
        "canon": canon,
    }

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("/* Generated by tools/build_canon.py - KJV, public domain.\n")
        fh.write("   Source: github.com/farskipper/kjv (bundled with VerseListener). */\n")
        fh.write("window.CANON_DATA=")
        json.dump(payload, fh, ensure_ascii=False, separators=(",", ":"))
        fh.write(";\n")

    size = os.path.getsize(OUT)
    print(f"books={len(order)} verses={count} -> {OUT} ({size/1024/1024:.2f} MB)")


if __name__ == "__main__":
    main()
